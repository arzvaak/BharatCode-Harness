/**
 * dsh-engram vocabulary: memory entries, relation edges, queries, and errors.
 * @module @kenz1117/dsh-engram/types
 */

/** Branded memory id: this type is used for ids across tool and storage boundaries; bare strings are rejected. */
declare const memoryIdBrand: unique symbol
export type MemoryId = string & { readonly [memoryIdBrand]: true }

/** Mint a branded id from any string (called by the storage layer before persisting). */
export function asMemoryId(raw: string): MemoryId {
  return raw as MemoryId
}

/** Branded entity id: the entity lexicon's primary key; bare strings are rejected across tool and storage boundaries. */
declare const entityIdBrand: unique symbol
export type EntityId = string & { readonly [entityIdBrand]: true }

/** Mint a branded entity id from any string (called by the storage layer before persisting). */
export function asEntityId(raw: string): EntityId {
  return raw as EntityId
}

/** Branded fact id: the fact chain's primary key; bare strings are rejected across tool and storage boundaries. */
declare const factIdBrand: unique symbol
export type FactId = string & { readonly [factIdBrand]: true }

/** Mint a branded fact id from any string (called by the storage layer before persisting). */
export function asFactId(raw: string): FactId {
  return raw as FactId
}

/** Branded belief id: the primary key of auto-consolidation products (observations); bare strings are rejected across tool and storage boundaries. */
declare const observationIdBrand: unique symbol
export type ObservationId = string & { readonly [observationIdBrand]: true }

/** Mint a branded belief id from any string (called by the storage layer before persisting). */
export function asObservationId(raw: string): ObservationId {
  return raw as ObservationId
}

/** Memory scope: user = private palace; project = project palace; shared = cross-agent shared palace (publicly readable). */
export type EngramScope = 'user' | 'project' | 'shared'

/** Whether a scope is the publicly readable shared scope. */
export function isSharedScope(scope: EngramScope): boolean {
  return scope === 'shared'
}

/** Memory kind: fact / preference / decision / episode / skill. */
export type EngramKind = 'fact' | 'preference' | 'decision' | 'episode' | 'skill'

/** Entry status: active participates in retrieval; archived (decayed/superseded) does not participate in retrieval but is recoverable; forgotten is a soft delete, recoverable. */
export type EngramStatus = 'active' | 'archived' | 'forgotten'

/** Relation edge type. supersedes semantics: from supersedes to. */
export type EngramEdgeType = 'supports' | 'contradicts' | 'refines' | 'related' | 'supersedes'

/** Memory usage effect (reward signal): success = effective after use, boost; failure = ineffective after use, down-weight; default = unverified. */
export type MemoryOutcome = 'success' | 'failure'

/** Five sensory channels: taste / sound / touch / sight / temperature. Classical mnemonics require imagery to hang on sensory hooks to improve recall. */
export type SensoryChannel = 'taste' | 'sound' | 'touch' | 'sight' | 'temperature'
/** A single sensory placard (e.g. "briny sea", "echoing bell", "coarse linen", "deep crimson", "metal cold"). */
export type SensoryToken = string
/** Emotional intensity: 0-1, borrowing the emotional memory's resistance to the forgetting curve — high intensity takes priority in tours. */
export type EmotionalValence = number

/** Imagery placard: maps an abstract entry to a concrete mental hook (a "bamboo slip stained with ink" rather than "user preferences"). Core of classical mnemonics: the more concrete, the better remembered. */
export interface ImageryLabel {
  /** A one-sentence concrete description (≤30 characters), e.g. "bamboo slip stained with ink", "copper bell in the rain". Default = null = not inscribed. */
  readonly caption: string | null
  /** List of sensory hooks (each corresponds to one SensoryChannel, optionally multiple dimensions sharing a sense). */
  readonly sensoryTags: readonly SensoryToken[]
  /** Emotional weight 0-1; 0 denotes a neutral statement. */
  readonly emotionalValence: EmotionalValence
  /** Whether generated by LLM speculation (true = candidate placard, unconfirmed by the user). */
  readonly provisional: boolean
}

/** Slot: a memory's fixed position in the palace (room name + index within the room). Core of the method of loci — only with fixed positions is the tour order stable. */
export interface Slot {
  /** Room name (default maps by kind: fact/preference/decision/episode/skill rooms; a full room auto-opens "<name>-2"). */
  readonly room: string
  /** Slot index within the room (from 1). */
  readonly index: number
}

/** Recall quality self-assessment (SM-2): 0 fully forgotten … 5 perfect recall; ≥3 counts as passing. */
export type ReviewGrade = 0 | 1 | 2 | 3 | 4 | 5

/** Spaced repetition scheduling state (a simplified SM-2). Entries once scheduled do not participate in automatic decay; review outcomes decide their fate. */
export interface ReviewSchedule {
  /** Next due time (epoch ms); null = not scheduled (the default for pre-existing entries). */
  readonly nextReviewAt: number | null
  /** Difficulty factor (SM-2 ease, floor 1.3, initial 2.5). */
  readonly easeFactor: number
  /** Current interval in days. */
  readonly intervalDays: number
  /** Consecutive passes (reset to zero on failure). */
  readonly reps: number
}

/** One memory. Source chain: v0.0.1 records sourceSessionId; since v0.2.0, auto-ingest fills in sourceRound/sourceSeq. */
export interface MemoryRecord {
  readonly id: MemoryId
  readonly scope: EngramScope
  readonly kind: EngramKind
  readonly content: string
  /** 0-1: importance, affects injection ordering and decay scheduling. */
  readonly importance: number
  /** 0-1: confidence; reinforced on hits, rolled back on distillation failure. */
  readonly confidence: number
  readonly status: EngramStatus
  /** Most recent usage effect report (written by engram_report; undefined when never reported). */
  readonly outcome?: MemoryOutcome
  readonly createdAt: number
  readonly lastAccessedAt: number
  readonly accessCount: number
  readonly sourceSessionId: string | null
  /** The turn within the source session (written by auto-ingest; null for explicit saves). */
  readonly sourceRound: number | null
  /** The source event seq (written by auto-ingest; null for explicit saves). */
  readonly sourceSeq: number | null
  /** Imagery placard (since schema v5; absent when not inscribed). */
  readonly imagery?: ImageryLabel
  /** Slot (since schema v6; absent when not slotted). */
  readonly slot?: Slot
  /** Imagery quality score 0-1 (since schema v6, heuristically stored at save time; absent when unscored). */
  readonly imageryScore?: number
  /** Spaced repetition schedule (since schema v6; absent when not yet scheduled). */
  readonly review?: ReviewSchedule
}

/** A memory relation edge. */
export interface MemoryEdge {
  readonly from: MemoryId
  readonly to: MemoryId
  readonly type: EngramEdgeType
  readonly createdAt: number
}

/** Entity category: the classification of mention objects the LLM extracts from memory content. */
export type EngramEntityKind = 'person' | 'project' | 'tool' | 'concept' | 'other'

/** Normalized comparison key: trim + collapse consecutive whitespace + lowercase (the first resolution version does only exact normalized matching, no fuzzy merging). */
export function normalizeEntityName(raw: string): string {
  return raw.trim().replace(/\s+/g, ' ').toLowerCase()
}

/** One entity: a named object extracted from memory (person/project/tool/concept), substored by the scope of its source memory. */
export interface EntityRecord {
  readonly id: EntityId
  /** Canonical name (the spelling at first creation). */
  readonly name: string
  readonly kind: EngramEntityKind
  /** Alias list (including canonical-name variants; on resolution it participates in normalized matching with the same weight as name). */
  readonly aliases: readonly string[]
  readonly createdAt: number
  readonly updatedAt: number
}

/** An entity mention: a single candidate in the LLM extraction output (the write path resolves it to an existing entity or creates a new one). */
export interface EntityMention {
  readonly name: string
  readonly kind: EngramEntityKind
  /** The mention's aliases (absent when there are no aliases). */
  readonly aliases?: readonly string[]
}

/** A fact mention: a single fact candidate in the LLM extraction output (entity must be an entity name that appears in the same batch's entity mentions). */
export interface FactMention {
  readonly entity: string
  readonly content: string
}

/** Admin list filter conditions (for the entity lexicon panel). */
export interface EntityListFilter {
  readonly kind?: EngramEntityKind
  /** Substring match on name and aliases_json (case-insensitive). */
  readonly q?: string
  readonly limit: number
  readonly offset: number
}

/** Entity list row: entity + count of linked active memories (for sorting and size display). */
export interface EntityListItem {
  readonly entity: EntityRecord
  readonly memoryCount: number
}

/** Entity list result (updated_at descending, with total). */
export interface EntityListResult {
  readonly items: readonly EntityListItem[]
  readonly total: number
}

/** Entity detail: the entity itself + its linked active memories (created time descending). */
export interface EntityDetail {
  readonly entity: EntityRecord
  readonly memories: readonly MemoryRecord[]
}

/** One fact: a one-sentence statement attached to an entity, with a validity window and a soft-invalidation chain (schema v11). */
export interface FactRecord {
  readonly id: FactId
  readonly entityId: EntityId
  /** The fact statement (one sentence). */
  readonly content: string
  /** The time the fact became valid (ms). */
  readonly validAt: number
  /** The time it was superseded (ms); null = still valid. */
  readonly invalidAt: number | null
  /** The successor fact id that supersedes this fact; null when not superseded. */
  readonly replacedBy: FactId | null
  /** The source memory id from which this fact was extracted; null when written directly by a tool. */
  readonly sourceNodeId: MemoryId | null
  readonly createdAt: number
  readonly updatedAt: number
}

/** Fact write request: entityId must be an entity in the same store; replaces declares an existing fact to supersede (when the target does not exist, written as no-replacement). */
export interface FactWriteInput {
  readonly entityId: EntityId
  readonly content: string
  readonly replaces?: FactId
  readonly sourceNodeId?: MemoryId
  /** The time the fact became valid (ms); defaults to the current time. */
  readonly validAt?: number
}

/** Fact chain query: filtered by entity; asOf limits a point-in-time perspective, includeInvalid expands the full chain. */
export interface FactListFilter {
  readonly entityId: EntityId
  /** Point-in-time query: returns facts still valid at that moment (valid_at <= asOf and invalid_at is null or > asOf). */
  readonly asOf?: number
  /** When true, do not filter out invalidated ones; return the whole history chain (including invalidated facts and their replacedBy back-references). */
  readonly includeInvalid?: boolean
  readonly limit: number
  readonly offset: number
}

/** Fact chain result (valid_at descending, with total). */
export interface FactListResult {
  readonly items: readonly FactRecord[]
  readonly total: number
}

/** Write request. Optional numeric fields, when absent, take defaults in the storage layer (do not explicitly pass undefined). */
export interface WriteInput {
  readonly scope: EngramScope
  readonly kind: EngramKind
  readonly content: string
  readonly importance?: number
  readonly confidence?: number
  readonly sourceSessionId?: string | null
  readonly sourceRound?: number
  readonly sourceSeq?: number
  /** Content vector (computed by the caller via the embedder); when absent, the entry does not participate in vector retrieval. */
  readonly embedding?: Float32Array
  /** Imagery placard (since schema v5; absent means not inscribed). */
  readonly imagery?: ImageryLabel
  /** Imagery quality score (computed and stored by the caller via scoreImagery; absent means not written). */
  readonly imageryScore?: number
  /** Slot (assigned by the caller via the slotting logic; absent means not slotted). */
  readonly slot?: Slot
  /** Initial review schedule: millisecond timestamp = a specified first due time; null = explicitly do not enter review scheduling (used for history backfill,
   *  to avoid a batch of backfilled entries flooding today's review queue at once); absent = decided by write-time automation. */
  readonly initialReviewAt?: number | null
}

/** Search request. */
export interface SearchQuery {
  readonly text: string
  readonly scopes: readonly EngramScope[]
  readonly limit?: number
  /**
   * Room routing (since schema v6): search only within the named rooms (the corridor index — decide which room to enter first).
   * Default searches the whole store; entries without a slot (empty slot_room) belong to no room and do not appear when rooms is specified.
   */
  readonly rooms?: readonly string[]
}

/** One search hit. */
export interface SearchHit {
  readonly record: MemoryRecord
  /** Fused score (RRF); higher is more relevant. */
  readonly score: number
  /** The channel this hit contributed on: fts keyword / vec semantic / both. */
  readonly via: 'fts' | 'vec' | 'both'
  /** When introduced via a one-hop relation edge expansion, the source entry id and edge type. */
  readonly viaEdge?: { readonly from: MemoryId; readonly type: EngramEdgeType }
  /** Encoding-specific cues (since schema v6): the entry ids of adjacent slots in the same room — reconstruct the encoding context at extraction time. */
  readonly cues?: { readonly neighbors: readonly MemoryId[] }
  /** Entities linked to the hit entry (since schema v10; absent when none). */
  readonly entities?: readonly { readonly id: EntityId; readonly name: string }[]
}

/** Search result: degraded=true means embeddings are missing/failed and only the keyword channel participates in ranking. */
export interface SearchResult {
  readonly hits: readonly SearchHit[]
  readonly degraded: boolean
}

/** Timeline query. since/until are epoch ms; topic is a substring match. */
export interface TimelineQuery {
  readonly since?: number
  readonly until?: number
  readonly topic?: string
  readonly scopes: readonly EngramScope[]
  /** Sort: default 'time' is reverse creation order; 'tour' is fixed tour-route slot order (entries not on the route are ordered by creation time at the end). */
  readonly order?: 'time' | 'tour'
  readonly limit?: number
}

/** Default window for the episode timeline's time-proximity expansion: anchor createdAt ± 60 minutes. */
export const EPISODE_PROXIMITY_MS_DEFAULT = 60 * 60 * 1000
/** Default result limit for the episode timeline. */
export const EPISODE_TIMELINE_LIMIT_DEFAULT = 100

/** Episode (episodic memory) timeline query: episodic cues independent of the general TimelineQuery.
 *  Default mode filters episode entries by since/until/sessionId and groups them by source session;
 *  when around is specified, it switches to time-proximity expansion mode (opening a window centered on the anchor's createdAt,
 *  ignoring since/until/sessionId — under window semantics, date filters would only truncate the expansion result). */
export interface EpisodeTimelineQuery {
  readonly scopes: readonly EngramScope[]
  /** Start time (epoch ms, inclusive); defaults to unlimited. */
  readonly since?: number
  /** End time (epoch ms, inclusive); defaults to unlimited. */
  readonly until?: number
  /** Only episodes from this source session (exact source_session_id match). */
  readonly sessionId?: string
  /** Time-proximity expansion anchor (any active memory id, not limited to episodes); loud failure when it does not exist in this store. */
  readonly around?: MemoryId
  /** Proximity window in ms (around mode); defaults to EPISODE_PROXIMITY_MS_DEFAULT. */
  readonly proximityMs?: number
  /** Result limit (count in group mode, neighbor count in around mode); defaults to EPISODE_TIMELINE_LIMIT_DEFAULT. */
  readonly limit?: number
}

/** A group of episodes grouped by source session (entries within a group in ascending creation order). */
export interface EpisodeSessionGroup {
  /** Source session id; null = no session source (explicit save or missing source chain). */
  readonly sessionId: string | null
  readonly episodes: readonly MemoryRecord[]
  /** Earliest creation time within the group (the group's sort key, the session's start). */
  readonly startedAt: number
  /** Latest creation time within the group (for displaying the session span). */
  readonly endedAt: number
  /** A one-sentence session summary generated at ingest time (displayed in the group header); absent when never generated. */
  readonly summary?: string
}

/** Episode timeline result. */
export interface EpisodeTimelineResult {
  /** Episodes grouped by session (groups in startedAt descending, the newest session first); an empty array in around mode. */
  readonly groups: readonly EpisodeSessionGroup[]
  /** Time-proximity expansion (returned when query.around is specified): the anchor entry + episode neighbors within the window
   *  (excluding the anchor itself, ascending creation order; limit bounds the neighbor count). */
  readonly around?: { readonly anchor: MemoryRecord; readonly neighbors: readonly MemoryRecord[] }
}

/** Update request: the old entry is turned archived and a supersedes edge is created (from=new, to=old). */
export interface UpdateInput {
  readonly id: MemoryId
  readonly scope: EngramScope
  readonly kind: EngramKind
  readonly content: string
  readonly importance?: number
  /** New content vector; when absent, inherits the old entry's vector. */
  readonly embedding?: Float32Array
  /** Imagery placard replacement; when absent, inherits the old entry's. */
  readonly imagery?: ImageryLabel
}

/** A single version record for a profile curated block (append-only version chain, the rollback data source). */
export interface ProfileBlockVersion {
  readonly scope: EngramScope
  /** Version number: monotonically increasing from 1; a rollback also produces a new version (history is never rewritten). */
  readonly version: number
  readonly content: string
  /** How it was produced: edit = manual/model edit; rollback = the content of a rolled-back historical version. */
  readonly source: 'edit' | 'rollback'
  readonly at: number
}

/** Current state of a profile curated block: takes priority over the auto-derived profile when injected at session start. */
export interface ProfileBlock {
  readonly scope: EngramScope
  readonly content: string
  /** Current version number (the optimistic-lock baseline: this value must be carried when editing). */
  readonly version: number
  readonly updatedAt: number
}

/** One operation log row (the audit view's row). */
export interface OperationLogRow {
  readonly at: number
  readonly op: string
  /** The operation target (an entry id or AUX); the whole-store activity view displays ownership by this. */
  readonly targetId: string
  readonly detail: string | null
}

/** One revision history row: a snapshot of the old content when update archives the old entry (content immutability audit). */
export interface MemoryRevision {
  readonly content: string
  readonly kind: string
  readonly importance: number
  readonly supersededAt: number
}

/** Audit view: entry + source chain + relation neighbors + operation log. */
export interface ReviewView {
  readonly record: MemoryRecord
  /** Who superseded this entry (supersedes edge from → this entry). */
  readonly supersededBy: readonly MemoryId[]
  /** Who this entry superseded (supersedes edge this entry → to). */
  readonly supersedes: readonly MemoryId[]
  readonly contradicts: readonly MemoryId[]
  readonly related: readonly MemoryId[]
  /** Revision history (old content snapshots, superseded time descending). */
  readonly revisions: readonly MemoryRevision[]
  /** The most recent 20 operation log entries involving this entry (time descending). */
  readonly operations: readonly OperationLogRow[]
}

/** Belief lifecycle status: active can be injected; stale has new evidence not yet incorporated, pending re-review; refuted was denied by evidence, kept only for audit. */
export type ObservationStatus = 'active' | 'stale' | 'refuted'

/**
 * A consolidated belief (observation): a one-sentence conclusion the auxiliary LLM consolidates from multiple raw memories.
 * Difference from ordinary memories: continuously refined (neighbors merged into the same one rather than repeatedly added), carries an
 * evidence chain (sourceIds + proofCount), and freshness can be re-reviewed (stale/refuted). Since schema v12.
 */
export interface ObservationRecord {
  readonly id: ObservationId
  readonly scope: EngramScope
  /** The one-sentence belief after consolidation. */
  readonly belief: string
  readonly status: ObservationStatus
  /** Raw memory ids supporting this belief (deduplicated union, continuously accumulated). */
  readonly sourceIds: readonly MemoryId[]
  /** Evidence count (= sourceIds length after dedup, redundantly stored for sorting). */
  readonly proofCount: number
  readonly createdAt: number
  readonly updatedAt: number
  /** The most recent time validated as holding through evidence re-review (form/refine/still all refresh it). */
  readonly lastValidatedAt: number
}

/** Write input for a new belief (sourceIds must have at least 1, and should be active memories in the same store). */
export interface ObservationWriteInput {
  readonly scope: EngramScope
  readonly belief: string
  readonly sourceIds: readonly MemoryId[]
  /** Belief vector (computed by the caller via the embedder); when absent, the belief does not participate in neighbor merging. */
  readonly embedding?: Float32Array
}

/** Belief list filter conditions. */
export interface ObservationListFilter {
  /** Default: no status filter. */
  readonly status?: ObservationStatus
  readonly limit: number
  readonly offset?: number
}

